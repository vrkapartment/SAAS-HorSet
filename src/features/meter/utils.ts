/**
 * เลขที่มิเตอร์วนกลับเป็น 0 — มิเตอร์ 4 หลักในไทยนับ 0000-9999
 *
 * ค่านี้ต้องตรงกับที่ทุกที่ในระบบใช้ ถ้าเปลี่ยนแปลว่าบิลเก่าทุกใบที่เคยข้ามรอบ
 * จะอธิบายยอดตัวเองไม่ได้อีกต่อไป
 */
export const METER_ROLLOVER_BASE = 10000

/**
 * จำนวนหน่วยที่ใช้ระหว่างสองการอ่านมิเตอร์
 *
 * curr >= prev  → นับตรง ๆ
 * curr <  prev  → ถือว่ามิเตอร์หมุนครบรอบ นับ (ฐาน - prev) + curr
 *                 เช่น 9,950 → 30 = (10,000 - 9,950) + 30 = 80 หน่วย
 *
 * ⚠️ กรณี curr < prev เป็นได้สองอย่าง: มิเตอร์หมุนครบรอบจริง หรือคนกรอกเลขผิด
 * ฟังก์ชันนี้ไม่รู้ว่าอันไหน จึงคิดแบบหมุนครบรอบเสมอตามพฤติกรรมเดิมของทั้งระบบ
 * หน้าที่แยกสองกรณีนี้อยู่ที่ฝั่งรับข้อมูล (ฟอร์มย้ายห้องบังคับให้ผู้ใช้ยืนยันก่อน)
 */
export function meterUnitsUsed(curr: number, prev: number): number {
  if (!Number.isFinite(curr) || !Number.isFinite(prev)) return 0
  if (curr >= prev) return curr - prev
  return (METER_ROLLOVER_BASE - prev) + curr
}

/**
 * เลขอ่านใหม่ที่ต่ำกว่าเลขเดิม อธิบายด้วย "มิเตอร์หมุนครบรอบ" ได้หรือไม่
 *
 * ใช้กันไม่ให้ผู้ใช้ติ๊ก "หมุนครบรอบ" กับเลขที่เป็นไปไม่ได้ เช่นติดลบ หรือเกินฐาน
 * ซึ่งจะทำให้ได้จำนวนหน่วยที่อธิบายไม่ได้บนใบแจ้งหนี้
 */
export function isPlausibleRollover(curr: number, prev: number): boolean {
  if (!Number.isFinite(curr) || !Number.isFinite(prev)) return false
  if (curr < 0 || prev < 0) return false
  if (curr >= METER_ROLLOVER_BASE || prev >= METER_ROLLOVER_BASE) return false
  return curr < prev
}
